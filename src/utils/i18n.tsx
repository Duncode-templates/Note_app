/**
 * Resolve translated string with multi-layered dictionary and alias fallback
 */
function resolveTranslation(lang: SupportedLanguage, key: string, fallback?: string): string {
  // 1. Direct match in ALL_LOCALES for current language
  if (ALL_LOCALES[lang] && ALL_LOCALES[lang][key]) {
    return ALL_LOCALES[lang][key];
  }

  // 2. Direct match in EXTRA_TRANSLATIONS for current language
  if (EXTRA_TRANSLATIONS[lang] && EXTRA_TRANSLATIONS[lang][key]) {
    return EXTRA_TRANSLATIONS[lang][key];
  }

  // 3. Direct match in TRANSLATIONS for current language
  const dict = TRANSLATIONS[lang];
  if (dict && dict[key]) {
    return dict[key];
  }

  // 4. Check alias keys for current language
  const aliases = KEY_ALIASES[key];
  if (aliases) {
    for (const alias of aliases) {
      if (ALL_LOCALES[lang] && ALL_LOCALES[lang][alias]) {
        return ALL_LOCALES[lang][alias];
      }
      if (EXTRA_TRANSLATIONS[lang] && EXTRA_TRANSLATIONS[lang][alias]) {
        return EXTRA_TRANSLATIONS[lang][alias];
      }
      if (dict && dict[alias]) {
        return dict[alias];
      }
    }
  }

  // 5. Fallback to English in ALL_LOCALES
  if (ALL_LOCALES.en && ALL_LOCALES.en[key]) {
    return ALL_LOCALES.en[key];
  }

  // 6. Fallback to English in EXTRA_TRANSLATIONS
  if (EXTRA_TRANSLATIONS.en && EXTRA_TRANSLATIONS.en[key]) {
    return EXTRA_TRANSLATIONS.en[key];
  }

  // 7. Fallback to English in TRANSLATIONS
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }

  // 8. Check aliases in English
  if (aliases) {
    for (const alias of aliases) {
      if (ALL_LOCALES.en && ALL_LOCALES.en[alias]) {
        return ALL_LOCALES.en[alias];
      }
      if (EXTRA_TRANSLATIONS.en && EXTRA_TRANSLATIONS.en[alias]) {
        return EXTRA_TRANSLATIONS.en[alias];
      }
      if (TRANSLATIONS.en && TRANSLATIONS.en[alias]) {
        return TRANSLATIONS.en[alias];
      }
    }
  }

  // 9. Explicit fallback argument or raw key
  return fallback !== undefined ? fallback : key;
}

/**
 * Detect the initial language from CrazyGames SDK v3, URL params, or device locale
 */
export function detectCrazyGamesLanguage(): SupportedLanguage {
  try {
    // 1. Check synchronous browser localStorage first
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (stored && TRANSLATIONS[stored as SupportedLanguage]) {
        return stored as SupportedLanguage;
      }
    }

    // 2. Check if user already manually selected a language in CrazyGames Data Storage
    const saved = crazyGamesSDK.getItemSync(LANGUAGE_STORAGE_KEY);
    if (saved && TRANSLATIONS[saved as SupportedLanguage]) {
      return saved as SupportedLanguage;
    }

    // 3. Check URL query parameters (CrazyGames passes ?lang= or ?locale=)
    if (typeof window !== 'undefined' && window.location) {
      const params = new URLSearchParams(window.location.search);
      const urlLang = params.get('lang') || params.get('locale');
      if (urlLang) {
        const clean = urlLang.toLowerCase().substring(0, 2);
        if (TRANSLATIONS[clean as SupportedLanguage]) {
          return clean as SupportedLanguage;
        }
      }
    }

    // 4. Check CrazyGames SDK v3 System Info Country Code
    const sysInfo = crazyGamesSDK.getSystemInfo();
    if (sysInfo?.countryCode) {
      const upper = sysInfo.countryCode.toUpperCase();
      const mapped = COUNTRY_TO_LANGUAGE_MAP[upper];
      if (mapped && TRANSLATIONS[mapped]) {
        return mapped;
      }
    }

    // 5. Fallback to browser navigator.language / languages
    if (typeof navigator !== 'undefined') {
      const navLang = navigator.language || (navigator.languages && navigator.languages[0]) || 'en';
      const clean = navLang.toLowerCase().substring(0, 2);
      if (TRANSLATIONS[clean as SupportedLanguage]) {
        return clean as SupportedLanguage;
      }
    }
  } catch (e) {
    console.warn('[i18n] Error detecting language:', e);
  }

  return 'en';
}

// Current active language variable
let currentActiveLanguage: SupportedLanguage = detectCrazyGamesLanguage();
const languageChangeListeners = new Set<(lang: SupportedLanguage) => void>();

/**
 * Get active language
 */
export function getActiveLanguage(): SupportedLanguage {
  return currentActiveLanguage;
}

/**
 * Set active language and broadcast update to all components
 */
export function setActiveLanguage(lang: SupportedLanguage): void {
  if (!TRANSLATIONS[lang]) return;
  currentActiveLanguage = lang;

  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    }
    crazyGamesSDK.setItem(LANGUAGE_STORAGE_KEY, lang).catch(() => {});
  } catch {}

  try {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    }
  } catch {}

  languageChangeListeners.forEach((fn) => {
    try {
      fn(lang);
    } catch (err) {
      console.error('[i18n] Listener error:', err);
    }
  });
}

/**
 * Subscribe to language changes
 */
export function subscribeLanguageChange(callback: (lang: SupportedLanguage) => void): () => void {
  languageChangeListeners.add(callback);
  return () => {
    languageChangeListeners.delete(callback);
  };
}

/**
 * Global synchronous translation lookup
 */
export function t(key: string, fallback?: string): string {
  return resolveTranslation(currentActiveLanguage, key, fallback);
}

// React Context for reactive app-wide internationalization
interface I18nContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, fallback?: string) => string;
  languages: LanguageInfo[];
  currentLangInfo: LanguageInfo;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
  languages: SUPPORTED_LANGUAGES,
  currentLangInfo: SUPPORTED_LANGUAGES[0],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<SupportedLanguage>(() => currentActiveLanguage);

  useEffect(() => {
    // Check again after CrazyGames SDK finishes init only if not set in localStorage
    crazyGamesSDK.init().then(() => {
      if (typeof localStorage !== 'undefined' && localStorage.getItem(LANGUAGE_STORAGE_KEY)) {
        return;
      }
      const detected = detectCrazyGamesLanguage();
      if (detected !== language) {
        currentActiveLanguage = detected;
        setLangState(detected);
      }
    });

    const unsub = subscribeLanguageChange((newLang) => {
      setLangState(newLang);
    });

    return unsub;
  }, []);

  const handleSetLanguage = useCallback((newLang: SupportedLanguage) => {
    setActiveLanguage(newLang);
    setLangState(newLang);
  }, []);

  const translateFn = useCallback(
    (key: string, fallback?: string) => {
      return resolveTranslation(language, key, fallback);
    },
    [language]
  );

  const currentLangInfo =
    SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage: handleSetLanguage,
        t: translateFn,
        languages: SUPPORTED_LANGUAGES,
        currentLangInfo,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

/**
 * Custom React hook to access translations in any component
 */
export function useTranslation() {
  return useContext(I18nContext);
}
