function writeLocaleFile(name, data) {
  const content = `export const ${name}: Record<string, string> = ${JSON.stringify(data, null, 2)};\n`;
  fs.writeFileSync(path.join(localesDir, `${name}.ts`), content, 'utf8');
  console.log(`Created ${name}.ts with ${Object.keys(data).length} keys`);
}

writeLocaleFile('en', en);

